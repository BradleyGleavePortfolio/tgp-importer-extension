export const VOCABULARY = Object.freeze(new Set([...WORDS, ...KEY_WORDS]));

// True when a decoded, non-empty path word may appear in clear.
export function isStructuralWord(word) {
  if (typeof word !== "string") return false;
  const lower = word.toLowerCase();
  return VERSION_MARKER.test(lower) || VOCABULARY.has(lower);
}

// True when a JSON key (snake_case, kebab-case or camelCase) is made only of
// vocabulary tokens, e.g. `client_id`, `createdAt`, `first-name`.
export function isStructuralKey(key) {
  if (typeof key !== "string" || key.length === 0 || key.length > 64)
    return false;
  const tokens = key
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .toLowerCase()
    .split(/[_-]+/)
    .filter((token) => token.length > 0);
  return tokens.length > 0 && tokens.every((token) => VOCABULARY.has(token));
}
